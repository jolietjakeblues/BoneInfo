def resolve_gemeente(naam):
    """BoneInfo Gemeente string -> TOOI concept URI, or None if unmapped."""
    if naam in TOOI_GEMEENTE:
        return TOOI_GEMEENTE[naam]
    if naam in GEMEENTE_ALIASES:
        return TOOI_GEMEENTE[GEMEENTE_ALIASES[naam]]
    return None


def resolve_provincie(naam):
    """BoneInfo Provincie string -> TOOI concept URI, or None if unmapped."""
    return TOOI_PROVINCIE.get(naam)
