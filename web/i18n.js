let current = DEFAULT_LANG;

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : DEFAULT_LANG;
  return current;
}

// t('key') of t('key', arg) -- functiewaarden (bv. resultCount) worden
// met de gegeven argumenten aangeroepen.
export function t(key, ...args) {
  const dict = STRINGS[current] || STRINGS[DEFAULT_LANG];
  const value = key.split('.').reduce((obj, part) => obj?.[part], dict);
  if (typeof value === 'function') return value(...args);
  return value ?? key;
}
